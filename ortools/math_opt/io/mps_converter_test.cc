using ::testing::EquivToProto;
using ::testing::HasSubstr;
using ::testing::status::IsOkAndHolds;
using ::testing::status::StatusIs;

constexpr double kInf = std::numeric_limits<double>::infinity();

ModelProto UnboundedIntegers() {
  Model model("unbounded_integers");
  const Variable x = model.AddContinuousVariable(1, kInf, "x");
  const Variable y = model.AddIntegerVariable(4, kInf, "y");
  model.Minimize(x + y);
  return model.ExportModel();
}

TEST(MpsToModelProtoTest, SimpleMps) {
  std::string simple_mps =
      R"mps(
NAME unbounded_integers
ROWS
 N  OBJ
COLUMNS
    x         OBJ       1
    MARKER    'MARKER'                 'INTORG'
    y         OBJ       1
    MARKER    'MARKER'                 'INTEND'
RHS
BOUNDS
 LO BND1      x         1
 LO BND1      y         4
ENDATA
)mps";
  EXPECT_THAT(MpsToModelProto(simple_mps),
              IsOkAndHolds(EquivToProto(UnboundedIntegers())));
}

TEST(ReadMpsFileTest, SimpleMps) {
  EXPECT_THAT(ReadMpsFile(ortools::GetDataDependencyFilepath(
                  "ortools/math_opt/io/test_data/"
                  "unbounded_integers.mps")),
              IsOkAndHolds(EquivToProto(UnboundedIntegers())));
}

TEST(ReadMpsFileTest, SimpleMpsGzipped) {
  EXPECT_THAT(ReadMpsFile(ortools::GetDataDependencyFilepath(
                  "ortools/math_opt/io/test_data/"
                  "unbounded_integers.mps.gz")),
              IsOkAndHolds(EquivToProto(UnboundedIntegers())));
}

TEST(ReadMpsFileTest, NotFoundFile) {
  EXPECT_THAT(ReadMpsFile(ortools::GetDataDependencyFilepath(
                  "ortools/math_opt/io/test_data/"
                  "file_that_cant_exist.mps")),
              StatusIs(absl::StatusCode::kNotFound,
                       HasSubstr("file_that_cant_exist.mps")));
}

TEST(ReadMpsFileTest, NotFoundFileGzipped) {
  EXPECT_THAT(ReadMpsFile(ortools::GetDataDependencyFilepath(
                  "ortools/math_opt/io/test_data/"
                  "file_that_cant_exist.mps.gz")),
              StatusIs(absl::StatusCode::kNotFound,
                       HasSubstr("file_that_cant_exist.mps.gz")));
}

TEST(ModelProtoToMpsTest, SimpleMIP) {
  Model model("unbounded_integers");
  const Variable x = model.AddContinuousVariable(1, kInf, "x");
  const Variable y = model.AddIntegerVariable(4, kInf, "y");
  model.Minimize(x + y);
  EXPECT_THAT(ModelProtoToMps(model.ExportModel()),
              IsOkAndHolds(R"mps(* Generated by MPModelProtoExporter
*   Name             : unbounded_integers
*   Format           : Free
*   Constraints      : 0
*   Variables        : 2
*     Binary         : 0
*     Integer        : 1
*     Continuous     : 1
NAME          unbounded_integers
ROWS
 N  COST
COLUMNS
  INTSTART  'MARKER'                            'INTORG'
    y       COST         1
  INTEND    'MARKER'                            'INTEND'
    x       COST         1
BOUNDS
 LO BOUND   x            1
 LI BOUND   y            4
ENDATA
)mps"));
}

